/* Exercise the actual generated offline pages, including bookmark restoration. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const {pathToFileURL}=require('node:url');
(async()=>{
  const root=path.resolve(__dirname,'..'), output=path.join(root,'outputs','browser-check');
  fs.mkdirSync(output,{recursive:true});
  const options={headless:true};
  if(process.env.CHROME) options.executablePath=process.env.CHROME;
  else if(fs.existsSync('C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe')) options.executablePath='C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
  const browser=await chromium.launch(options),page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  let checks=0;
  const open=async file=>page.goto(pathToFileURL(path.join(root,'docs',file)).href);
  try {
    await open('index.html');
    await page.screenshot({path:path.join(output,'homepage-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));checks++;
    await page.screenshot({path:path.join(output,'homepage-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.getByRole('link',{name:'患者与缺失值交互',exact:true}).click();
    await page.selectOption('#feature','bgr');await page.selectOption('#view','complete_case');
    await page.selectOption('#patient','43');
    assert.match(await page.locator('#patient-detail').innerText(),/整行剔除/);checks++;
    await page.selectOption('#deletion-rule','core5');
    assert.match(await page.locator('#patient-detail').innerText(),/204/);
    assert.doesNotMatch(await page.locator('#patient-detail').innerText(),/整行剔除/);checks++;
    assert.match(await page.locator('#people').innerText(),/165 \/ 250/);checks++;
    await page.selectOption('#scatter-group','ckd');await page.selectOption('#method','spearman');
    const linear=await page.locator('#pair-value').innerText();
    await page.selectOption('#scatter-scale','log');
    assert.equal(await page.locator('#pair-value').innerText(),linear);checks++;
    await page.reload();assert.equal(await page.locator('#deletion-rule').inputValue(),'core5');
    assert.equal(await page.locator('#patient').inputValue(),'43');checks++;
    await page.locator('#pca-link').click();
    assert.equal(await page.locator('#patient').inputValue(),'43');checks++;
    await page.selectOption('#strip-range','central');
    assert.match(await page.locator('#strip-key').innerText(),/超界/);checks++;
    assert.equal(await page.locator('#strip-scale').inputValue(),'z');checks++;
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));checks++;
    await page.screenshot({path:path.join(output,'scales-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.screenshot({path:path.join(output,'scales-desktop.png'),fullPage:true});
    await page.locator('#cohort-link').click();
    assert.equal(await page.locator('#patient').inputValue(),'43');checks++;
    await open('results/figures/cohort.html');
    await page.getByRole('button',{name:'病例 43',exact:true}).click();
    assert.equal(await page.locator('#patient').inputValue(),'43');checks++;
    await page.selectOption('#deletion-rule','current');
    assert.match(await page.locator('#rule-comparison').innerText(),/356 \/ 400/);checks++;
    await page.selectOption('#scatter-view','observed');
    assert.equal(await page.locator('#linked-view').isChecked(),false);checks++;
    assert.match(await page.locator('#pair-value').innerText(),/0.586/);checks++;
    await page.selectOption('#method','spearman');
    assert.match(await page.locator('#pair-value').innerText(),/0.703/);checks++;
    await page.getByRole('button',{name:'血红蛋白填补',exact:true}).click();
    assert.match(await page.locator('#patient-detail').innerText(),/该项已填补/);checks++;
    await page.getByRole('button',{name:'病例 43',exact:true}).click();
    await page.screenshot({path:path.join(output,'cohort-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));checks++;
    await page.screenshot({path:path.join(output,'cohort-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:900});await open('presentation/deck.html');
    assert.equal(await page.locator('.slide').count(),8);checks++;
    for(let i=1;i<=8;i++){
      await page.keyboard.press(String(i));
      await page.screenshot({path:path.join(output,`slide-${i}.png`)});
      const overflow=await page.locator('.slide.active').evaluate(el=>el.scrollHeight>el.clientHeight+2);
      assert.equal(overflow,false,`Slide ${i} content overflow`);checks++;
    }
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({checks,errors},null,2));
    console.log(`Browser checks passed: ${checks}; page errors: ${errors.length}. Screenshots: ${output}`);
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
